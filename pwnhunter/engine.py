# Linux CTF targets overwhelmingly use 4 KiB mappings.  mmap grants whole
# pages, so treating the requested byte count as the exact capacity creates
# false positives for accesses that remain inside the final rounded page.
_MMAP_PAGE_SIZE = 0x1000

# Linux rejects larger scatter/gather arrays before reading their descriptors.
_IOV_MAX = 1024


