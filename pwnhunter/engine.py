@dataclass(slots=True)
class _TaintState:
    """Field-sensitive hostile-data locations used within one function."""

    whole: set[str] = field(default_factory=set)
    fields: set[tuple[str, int]] = field(default_factory=set)
    regions: set[tuple[str, int]] = field(default_factory=set)

    @property
    def size(self) -> int:
        return len(self.whole) + len(self.fields) + len(self.regions)

    def has_object_data(self, key: str) -> bool:
        return key in self.whole or any(
            candidate == key
            for candidate, _ in (*self.fields, *self.regions)
        )


class Analyzer:
    """Analyze normalized functions without requiring IDA at runtime."""

    def __init__(
        self,
        summaries: SummaryIndex | None = None,
        program_buffers: dict[str, BufferInfo] | None = None,
        record_capacity_roots: frozenset[str] | None = None,
        custom_release_arguments: dict[int, frozenset[int]] | None = None,
        retained_free_origins: dict[str, tuple[int, ...]] | None = None,
    ):
        self.summaries = summaries or SummaryIndex()
        self.program_buffers = program_buffers or {}
        self.record_capacity_roots = record_capacity_roots or frozenset()
        self.custom_release_arguments = custom_release_arguments or {}
        self.retained_free_origins = retained_free_origins or {}

    @classmethod
    def analyze_program(cls, functions: list[FunctionIR]) -> list[Finding]:
        summaries = SummaryBuilder().build(functions)
        analyzer = cls.for_program(functions, summaries)
        findings = [
            finding
            for function in functions
            for finding in analyzer.analyze_function(function)
        ]
        unique = {finding.fingerprint: finding for finding in findings}
        return sorted(
            unique.values(),
            key=lambda finding: (-int(finding.severity), finding.ea, finding.rule_id),
        )

    @classmethod
    def for_program(
        cls, functions: list[FunctionIR], summaries: SummaryIndex
    ) -> "Analyzer":
        """Build cross-function facts for global/static object slots."""

        probe = cls(summaries)
        program_buffers: dict[str, BufferInfo] = {}
        for _ in range(max(2, len(functions) + 1)):
            changed = False
            probe.program_buffers = program_buffers
            for function in functions:
                for key, candidate in probe._infer_buffers(function).items():
                    if not key.startswith("g:"):
                        continue
                    existing = program_buffers.get(key)
                    if existing is None:
                        program_buffers[key] = candidate
                        changed = True
                    elif (
                        existing.capacity != candidate.capacity
                        and existing.capacity is not None
                    ):
                        merged = replace(existing, capacity=None, precise=False)
                        if merged != existing:
                            program_buffers[key] = merged
                            changed = True
            if not changed:
                break
        record_capacity_roots = probe._infer_record_capacity_roots(functions)
        custom_release_arguments = probe._infer_custom_release_arguments(functions)
        probe.custom_release_arguments = custom_release_arguments
        retained_free_origins = probe._infer_retained_free_origins(functions)
        return cls(
            summaries,
            program_buffers,
            record_capacity_roots,
            custom_release_arguments,
            retained_free_origins,
        )

    def analyze_function(self, function: FunctionIR) -> list[Finding]:
        tainted = self._compute_taint(function)
        buffers = self._infer_buffers(function)
        findings: list[Finding] = []

        calls = [s for s in function.statements if isinstance(s, Call)]
        for call in calls:
            modeled_calls = self._modeled_calls(call)
            effective_calls = (call, *modeled_calls)
            summary = self._summary_for_call(call)
            summarized_read_sinks = {
                normalize_symbol(effect.sink)
                for effect in summary.reads
            } if summary is not None else set()
            for effective_call in effective_calls:
                call_findings: list[Finding] = []
                call_findings.extend(
                    self._check_format(function, effective_call, tainted)
                )
                call_findings.extend(
                    self._check_unbounded(function, effective_call, tainted, buffers)
                )
                call_findings.extend(
                    self._check_bounded(function, effective_call, tainted, buffers)
                )
                if (
                    effective_call is not call
                    and normalize_symbol(effective_call.name)
                    in summarized_read_sinks
                ):
                    # A copy wrapper exports both a WriteEffect and a
                    # ReadEffect. Keep the latter's internal sink location;
                    # otherwise the materialized write duplicates the same
                    # source overread at the outer call site.
                    call_findings = [
                        finding
                        for finding in call_findings
                        if finding.rule_id not in {"BUF-007", "BUF-013"}
                    ]
                findings.extend(self._annotate_origin(call_findings, effective_call))
            findings.extend(
                self._check_summary_reads(function, call, tainted, buffers)
            )
            findings.extend(
                self._check_iovec_reads(function, call, buffers)
            )
            findings.extend(
                self._check_iovec_writes(function, call, tainted, buffers)
            )
            findings.extend(
                self._check_message_reads(function, call, buffers)
            )
            findings.extend(
                self._check_message_writes(function, call, tainted, buffers)
            )
            findings.extend(self._check_scanf(function, call, buffers))

        findings.extend(self._check_integer_flows(function, tainted, buffers))
        findings.extend(self._check_inline_writes(function, tainted, buffers))
        findings.extend(
            self._check_accumulating_inline_writes(function, tainted, buffers)
        )
        findings.extend(
            self._check_global_index_guard_mismatches(function, tainted)
        )
        findings.extend(self._check_inline_window_writes(function))
        findings.extend(self._check_cstring_termination(function, tainted, buffers))
        if function.blocks and function.entry_block is not None:
            findings.extend(LifecycleDataflow(self.summaries).analyze(function))
        else:
            findings.extend(self._check_lifetimes(function))
        findings.extend(self._check_retained_frees(function))
        findings.extend(self._check_indirect_retained_global_calls(function))
        findings.extend(self._check_refcount_release_bypasses(function))
        unique = {finding.fingerprint: finding for finding in findings}
        reduced = self._suppress_subsumed_findings(list(unique.values()))
        return sorted(
            reduced,
            key=lambda finding: (-int(finding.severity), finding.ea, finding.rule_id),
        )

    @staticmethod
    def _suppress_subsumed_findings(findings: list[Finding]) -> list[Finding]:
        """Prefer a structural root-cause rule over a generic same-site symptom."""

        inline_window_sites = {
            (finding.function_ea, finding.ea)
            for finding in findings
            if finding.rule_id == "BUF-008"
        }
        return [
            finding
            for finding in findings
            if not (
                finding.rule_id == "INT-002"
                and (finding.function_ea, finding.ea) in inline_window_sites
            )
        ]

    def _compute_taint(self, function: FunctionIR) -> _TaintState:
        tainted = _TaintState()
        trusted_handles = self._trusted_input_handles(function)

        # A fixed point makes the result independent of decompiler traversal
        # order and handles simple chains such as a = b; c = a.
        for _ in range(max(4, len(function.statements) + 1)):
            before = tainted.size
            tokenizer_sessions: dict[str, bool] = {}
            for statement in sorted(
                function.statements, key=lambda item: item.order
            ):
                if isinstance(statement, Return):
                    continue
                if isinstance(statement, Assignment):
                    tokenizer_tainted = self._advance_tokenizer_taint(
                        statement.value, tokenizer_sessions, tainted
                    )
                    if statement.target.key and (
                        tokenizer_tainted is True
                        or self._is_tainted(statement.value, tainted)
                    ):
                        self._mark_tainted_destination(tainted, statement.target)
                    continue

                name = normalize_symbol(statement.name)
                self._advance_tokenizer_call_taint(
                    name, statement.args, tokenizer_sessions, tainted
                )
                for index in INPUT_WRITES.get(name, ()):
                    argument = self._arg(statement, index)
                    if (
                        argument
                        and argument.key
                        and not self._trusted_direct_input(
                            statement, name, trusted_handles
                        )
                    ):
                        self._mark_tainted_destination(tainted, argument)

                iovec_consumers = self._iovec_write_consumers(statement)
                if any(
                    self._iovec_input_is_external(
                        statement, sink, effect, trusted_handles
                    )
                    for sink, _, _, effect in iovec_consumers
                ):
                    for input_write in self._materialized_iovec_writes(
                        function, statement
                    ):
                        destination = self._arg(input_write, 1)
                        if destination is not None and destination.key:
                            self._mark_tainted_destination(
                                tainted, destination
                            )

                if self._message_write_consumers(statement):
                    for input_write in self._materialized_message_writes(
                        function, statement
                    ):
                        destination = self._arg(input_write, 1)
                        if destination is not None and destination.key:
                            self._mark_tainted_destination(
                                tainted, destination
                            )

                scanf = SCANF_SPECS.get(name)
                if scanf:
                    _, first_output, source_index = scanf
                    source_tainted = source_index is None
                    if source_index is not None:
                        source = self._arg(statement, source_index)
                        source_tainted = bool(source and self._is_tainted(source, tainted))
                    if source_tainted:
                        for argument in statement.args[first_output:]:
                            if argument.key:
                                self._mark_tainted_destination(tainted, argument)

                copy = COPY_SPECS.get(name)
                if copy:
                    destination_index, source_index, _ = copy
                    destination = self._arg(statement, destination_index)
                    source = self._arg(statement, source_index)
                    if (
                        destination
                        and destination.key
                        and source
                        and self._is_tainted(source, tainted)
                    ):
                        self._mark_tainted_destination(tainted, destination)

                summary = self._summary_for_call(statement)
                if summary is not None:
                    for effect in summary.writes:
                        handle_tainted = bool(effect.input_handles) and any(
                            (handle := value.resolve(statement.args)) is None
                            or not self._is_trusted_input_handle(
                                handle, statement.order, trusted_handles
                            )
                            for value in effect.input_handles
                        )
                        destination_tainted = (
                            effect.taints_destination
                            or handle_tainted
                            or any(
                                (source := value.resolve(statement.args)) is not None
                                and self._is_tainted(source, tainted)
                                for value in effect.taint_sources
                            )
                        )
                        if not destination_tainted:
                            continue
                        destination = effect.destination.resolve(statement.args)
                        if destination is not None and destination.key:
                            self._mark_tainted_destination(tainted, destination)

            if tainted.size == before:
                break
        return tainted

    def _advance_tokenizer_taint(
        self,
        expression: Expr,
        sessions: dict[str, bool],
        tainted: _TaintState,
    ) -> bool | None:
        value = expression.unwrapped()
        if value.kind != "call":
            return None
        name = normalize_symbol(value.callee or "")
        return self._advance_tokenizer_call_taint(
            name, value.children, sessions, tainted
        )

    def _advance_tokenizer_call_taint(
        self,
        name: str,
        arguments: tuple[Expr, ...],
        sessions: dict[str, bool],
        tainted: _TaintState,
    ) -> bool | None:
        """Advance one stateful tokenizer session in statement order."""

        input_index = STATEFUL_TAINT_RETURNS.get(name)
        if input_index is None or input_index >= len(arguments):
            return None
        source = arguments[input_index]
        other_tainted = any(
            self._is_tainted(argument, tainted)
            for index, argument in enumerate(arguments)
            if index != input_index
        )
        if self._eval_int(source) == 0:
            result = sessions.get(name, False) or other_tainted
        else:
            result = self._is_tainted(source, tainted) or other_tainted
        sessions[name] = result
        return result

    @classmethod
    def _mark_tainted_destination(
        cls, tainted: _TaintState, expression: Expr
    ) -> None:
        """Record bytes written through an lvalue or destination pointer.

        Precise record fields stay separate. Pointer arithmetic with a
        positive constant prefix marks the trailing inline region, while an
        unresolved base write conservatively taints the whole object.
        """

        value = expression.unwrapped()
        if value.kind == "address" and value.children:
            cls._mark_tainted_lvalue(tainted, value.children[0])
            return
        if value.kind in {"member", "index", "deref"}:
            cls._mark_tainted_lvalue(tainted, value)
            return
        if value.kind in {"var", "global"} and value.key is not None:
            tainted.whole.add(value.key)
            return
        if value.key is None:
            return
        constants = {
            constant
            for constant in cls._nonindex_constant_leaves(value)
            if constant > 0
        }
        if constants:
            tainted.regions.add((value.key, max(constants)))
        else:
            tainted.whole.add(value.key)

    @classmethod
    def _mark_tainted_lvalue(
        cls, tainted: _TaintState, expression: Expr
    ) -> None:
        location = cls._precise_memory_location(expression)
        if location is not None:
            tainted.fields.add(location)
        elif expression.key is not None:
            tainted.whole.add(expression.key)

    @classmethod
    def _precise_memory_location(
        cls, expression: Expr
    ) -> tuple[str, int] | None:
        """Return a constant record slot, rejecting dynamic array accesses."""

        value = expression.unwrapped()
        if value.key is None or value.kind not in {"member", "index", "deref"}:
            return None
        if value.kind == "member":
            return value.key, value.offset
        if value.kind == "index":
            if len(value.children) < 2 or cls._eval_int(value.children[1]) is None:
                return None
            return value.key, value.offset
        if not value.children:
            return value.key, value.offset
        address = value.children[0].unwrapped()
        if address.kind in {"var", "global", "address"}:
            return value.key, value.offset
        if address.kind == "op" and address.op in {"add", "sub"}:
            dynamic = [
                child
                for child in address.children
                if child.key != value.key and cls._eval_int(child) is None
            ]
            if not dynamic:
                return value.key, value.offset
        return None

    @staticmethod
    def _trusted_input_handles(function: FunctionIR) -> dict[str, int]:
        """Return object keys initialized from fixed trusted pseudo-files."""

        trusted: dict[str, int] = {}
        for statement in sorted(function.statements, key=lambda item: item.order):
            if isinstance(statement, Assignment):
                if (
                    statement.target.key
                    and statement.value.string in _TRUSTED_KERNEL_INPUT_PATHS
                ):
                    trusted.setdefault(statement.target.key, statement.order)
                continue
            if not isinstance(statement, Call):
                continue
            name = normalize_symbol(statement.name)
            copy = UNBOUNDED_WRITE_SPECS.get(name)
            if copy is None or copy[1] is None:
                continue
            destination_index, source_index = copy
            if (
                destination_index >= len(statement.args)
                or source_index >= len(statement.args)
            ):
                continue
            destination = statement.args[destination_index]
            source = statement.args[source_index]
            if (
                destination.key
                and source.string in _TRUSTED_KERNEL_INPUT_PATHS
            ):
                trusted.setdefault(destination.key, statement.order)
        return trusted

    def _trusted_direct_input(
        self,
        call: Call,
        name: str,
        trusted_handles: dict[str, int],
    ) -> bool:
        if name not in {
            "read",
            "pread",
            "readv",
            "preadv",
            "preadv64",
            "preadv2",
        } or not call.args:
            return False
        return self._is_trusted_input_handle(
            call.args[0], call.order, trusted_handles
        )

    def _iovec_input_is_external(
        self,
        call: Call,
        sink: str,
        effect: IovecWriteEffect | None,
        trusted_handles: dict[str, int],
    ) -> bool:
        if effect is None:
            return not self._trusted_direct_input(
                call, normalize_symbol(sink), trusted_handles
            )
        if effect.taints_destination or not effect.input_handles:
            return True
        return any(
            (handle := value.resolve(call.args)) is None
            or not self._is_trusted_input_handle(
                handle, call.order, trusted_handles
            )
            for value in effect.input_handles
        )

    @staticmethod
    def _is_trusted_input_handle(
        expression: Expr,
        order: int,
        trusted_handles: dict[str, int],
    ) -> bool:
        keys = expression.dependencies()
        if expression.key:
            keys.add(expression.key)
        return any(
            key in trusted_handles and trusted_handles[key] < order
            for key in keys
        )

    def _is_tainted(self, expression: Expr, tainted: _TaintState) -> bool:
        if expression.kind in {"const", "string"}:
            return False
        if expression.key in tainted.whole:
            return True
        if expression.kind in {"deref", "member", "index"}:
            # The operands of a load describe *where* the value came from,
            # not the value stored there.  In particular, an attacker-chosen
            # array index must not taint a trusted size table entry merely
            # because the index appears in ``Expr.children``.  A genuinely
            # tainted memory object is still handled by the key check above.
            location = self._precise_memory_location(expression)
            if location is None:
                return bool(
                    expression.key
                    and tainted.has_object_data(expression.key)
                )
            key, offset = location
            return location in tainted.fields or any(
                candidate == key and offset >= start
                for candidate, start in tainted.regions
            )
        if (
            expression.kind in {"var", "global"}
            and expression.key is not None
            and tainted.has_object_data(expression.key)
        ):
            # Passing an object pointer to a parser exposes its tainted
            # fields/inline region even though the pointer value is trusted.
            return True
        if expression.key is not None and tainted.regions:
            constants = {
                constant
                for constant in self._nonindex_constant_leaves(expression)
                if constant >= 0
            }
            if constants and any(
                key == expression.key and max(constants) >= start
                for key, start in tainted.regions
            ):
                return True
        if expression.kind == "call":
            name = normalize_symbol(expression.callee or "")
            if name in RETURN_SOURCES:
                return True
            if name in TAINT_PASSTHROUGH_RETURNS:
                return any(self._is_tainted(child, tainted) for child in expression.children)
            summary = self.summaries.lookup(
                expression.callee or "", expression.callee_ea
            )
            if summary is not None:
                if summary.returns_external_input:
                    return True
                return any(
                    index < len(expression.children)
                    and self._is_tainted(expression.children[index], tainted)
                    for index in summary.return_taint_arguments
                )
            return False
        return any(self._is_tainted(child, tainted) for child in expression.children)

    def _infer_buffers(self, function: FunctionIR) -> dict[str, BufferInfo]:
        buffers = dict(self.program_buffers)
        buffers.update(function.buffers)
        assignments = [
            statement
            for statement in function.statements
            if isinstance(statement, Assignment) and statement.target.key
        ]

        # Direct allocation facts are merged monotonically. Reassigning the
        # same variable with different allocation sizes makes its capacity
        # unknown instead of causing a fixed-point oscillation.
        for statement in assignments:
            target_key = statement.target.key
            value = statement.value
            if statement.target.kind not in {"var", "global"} or statement.target.offset:
                continue
            size_parts = self._allocation_size_parts(value)
            if size_parts is None:
                continue
            allocator = self._allocation_name(value)
            storage = "mapped" if allocator in {"mmap", "mmap64"} else "heap"
            capacity = self._product_value(size_parts)
            if storage == "mapped" and capacity is not None and capacity > 0:
                capacity = (
                    (capacity + _MMAP_PAGE_SIZE - 1) // _MMAP_PAGE_SIZE
                ) * _MMAP_PAGE_SIZE
            candidate = BufferInfo(
                key=target_key,
                name=statement.target.text or target_key,
                storage=storage,
                capacity=capacity,
                precise=capacity is not None,
            )
            existing = buffers.get(target_key)
            if existing is None:
                buffers[target_key] = candidate
            elif existing.storage in {"heap", "mapped"} and (
                existing.storage != storage or existing.capacity != capacity
            ):
                buffers[target_key] = replace(existing, capacity=None, precise=False)

        changed = True
        while changed:
            changed = False
            for statement in assignments:
                target_key = statement.target.key
                value = statement.value
                if (
                    statement.target.kind not in {"var", "global"}
                    or statement.target.offset
                    or target_key in buffers
                    or value.key not in buffers
                    or value.kind not in {"var", "global", "address", "cast", "op"}
                    or not self._is_buffer_alias_expression(value, value.key)
                ):
                    continue
                source = buffers[value.key]
                buffers[target_key] = replace(
                    source,
                    key=target_key,
                    name=statement.target.text or target_key,
                    capacity=(
                        None
                        if source.capacity is None
                        else max(0, source.capacity - max(0, value.offset))
                    ),
                    # A pointer alias does not preserve the exact source-object
                    # base.  In particular, Hex-Rays renders incrementing
                    # vector loops as alias[-1]; claiming a constant OOB from
                    # that recovered offset is unsound.
                    precise=(
                        source.precise
                        if target_key == source.key or source.storage != "stack"
                        else False
                    ),
                )
                changed = True
        return buffers

    @classmethod
    def _is_buffer_alias_expression(cls, expression: Expr, source_key: str) -> bool:
        """Return whether an expression denotes an object's address.

        Hex-Rays retains the global key while loading a pointer from a global
        table, for example ``(T *)(global_ptr[0] + 32)``.  That value points to
        the allocation stored in the table; it is not an alias of the table's
        eight-byte slot.  Only propagate capacity through address-preserving
        casts and pointer arithmetic whose base is the object itself.
        """

        if expression.key != source_key:
            return False
        if expression.kind in {"var", "global", "address"}:
            return True
        if expression.kind == "cast" and expression.children:
            return cls._is_buffer_alias_expression(expression.children[0], source_key)
        if expression.kind == "op" and expression.op in {"add", "sub"}:
            return any(
                cls._is_buffer_alias_expression(child, source_key)
                for child in expression.children
            )
        # index/member/deref expressions load a value from the object.  Their
        # inherited key identifies provenance, not an address-preserving alias.
        return False

    def _check_format(
        self, function: FunctionIR, call: Call, tainted: _TaintState
    ) -> list[Finding]:
        name = normalize_symbol(call.name)
        format_index = FORMAT_ARGUMENTS.get(name)
        if format_index is None:
            return []
        expression = self._arg(call, format_index)
        if expression is None or expression.string is not None:
            return []

        proven_tainted = self._is_tainted(expression, tainted)
        severity = Severity.HIGH if proven_tainted else Severity.MEDIUM
        confidence = "High" if proven_tainted else "Medium"
        qualifier = "attacker-controlled" if proven_tainted else "non-literal"
        return [
            self._finding(
                function,
                call,
                "FMT-001",
                "Format string",
                severity,
                confidence,
                f"{qualifier} format reaches {name}",
                f"format={expression.text or '<expression>'}",
            )
        ]

    def _check_unbounded(
        self,
        function: FunctionIR,
        call: Call,
        tainted: _TaintState,
        buffers: dict[str, BufferInfo],
    ) -> list[Finding]:
        name = normalize_symbol(call.name)
        spec = UNBOUNDED_WRITE_SPECS.get(name)
        if spec is None:
            return []
        destination_index, source_index = spec
        destination = self._arg(call, destination_index)
        if destination is None:
            return []
        if self._active_fortify_capacity(call, tainted) is not None:
            # A trusted compiler object size makes the wrapper terminate
            # before a destination overflow.  Source-side C-string reads are
            # checked independently by the termination analysis.
            return []
        buffer = self._buffer_for(destination, buffers)

        # gets() is intrinsically unbounded even when the destination type was
        # not recovered by the decompiler.
        if name == "gets":
            storage = buffer.storage if buffer else "unknown"
            capacity = self._available_capacity(destination, buffer)
            return [
                self._finding(
                    function,
                    call,
                    "BUF-001",
                    f"{storage.title()} buffer overflow",
                    Severity.CRITICAL,
                    "High",
                    "gets performs an unbounded write",
                    self._destination_evidence(destination, capacity),
                )
            ]

        if buffer is None:
            return []

        capacity = self._available_capacity(destination, buffer)
        if name in {
            "sprintf",
            "vsprintf",
            "__sprintf_chk",
            "__vsprintf_chk",
        }:
            format_expression = self._arg(call, FORMAT_ARGUMENTS.get(name))
            available = self._available_physical_capacity(destination, buffer)
            if available is None:
                available = capacity
            exact = self._literal_plain_format_size(format_expression)
            if exact is not None and available is not None:
                if exact <= available:
                    return []
                return [
                    self._finding(
                        function,
                        call,
                        "BUF-002",
                        f"{buffer.storage.title()} buffer overflow",
                        Severity.CRITICAL,
                        "High",
                        f"literal output exceeds {name} destination",
                        (
                            f"literal output requires {exact} bytes; "
                            f"{self._destination_evidence(destination, capacity)}"
                        ),
                    )
                ]
            upper = self._literal_format_upper_bound(call, format_expression)
            if upper is not None and available is not None and upper <= available:
                return []
        source = self._arg(call, source_index) if source_index is not None else None
        if (
            name
            in {
                "strcpy",
                "stpcpy",
                "wcscpy",
                "__strcpy_chk",
                "__stpcpy_chk",
            }
            and source is not None
            and source.string is not None
            and capacity is not None
        ):
            required = len(source.string.encode("utf-8")) + 1
            available = self._available_physical_capacity(destination, buffer)
            if available is None:
                available = capacity
            if required <= available:
                return []
            evidence = (
                f"literal requires {required} bytes; "
                f"{self._destination_evidence(destination, capacity)}"
            )
            confidence = "High"
            severity = Severity.CRITICAL
        else:
            source_tainted = bool(source and self._is_tainted(source, tainted))
            evidence = self._destination_evidence(destination, capacity)
            if source is not None:
                evidence += f"; source={source.text or '<expression>'}"
            confidence = "High" if source_tainted else "Medium"
            severity = Severity.HIGH

        return [
            self._finding(
                function,
                call,
                "BUF-002",
                f"{buffer.storage.title()} buffer overflow",
                severity,
                confidence,
                f"{name} writes without a destination bound",
                evidence,
            )
        ]

    @staticmethod
    def _literal_plain_format_size(
        format_expression: Expr | None,
    ) -> int | None:
        """Return exact output bytes for literal text containing only ``%%``."""

        if format_expression is None or format_expression.string is None:
            return None
        text = format_expression.string
        output = bytearray()
        cursor = 0
        while cursor < len(text):
            if text[cursor] != "%":
                output.extend(text[cursor].encode("utf-8"))
                cursor += 1
                continue
            if cursor + 1 >= len(text) or text[cursor + 1] != "%":
                return None
            output.extend(b"%")
            cursor += 2
        return len(output) + 1

    @staticmethod
    def _literal_format_upper_bound(
        call: Call, format_expression: Expr | None
    ) -> int | None:
        """Return a conservative byte bound for a simple literal sprintf."""

        if format_expression is None or format_expression.string is None:
            return None
        text = format_expression.string
        total = 1  # trailing NUL
        cursor = 0
        argument_index = (FORMAT_ARGUMENTS.get(normalize_symbol(call.name)) or 0) + 1
        pattern = re.compile(
            r"%(?:[-+ #0']*)(?P<width>\d+)?(?:\.(?P<precision>\d+))?"
            r"(?P<length>hh|h|ll|l|j|z|t|L)?(?P<conversion>[diouxXfFeEgGaAcsp%])"
        )
        for match in pattern.finditer(text):
            total += len(text[cursor : match.start()].encode("utf-8"))
            cursor = match.end()
            conversion = match.group("conversion")
            width = int(match.group("width") or 0)
            precision_text = match.group("precision")
            precision = int(precision_text) if precision_text is not None else None
            length = match.group("length") or ""
            if conversion == "%":
                total += 1
                continue
            argument = call.args[argument_index] if argument_index < len(call.args) else None
            argument_index += 1
            if conversion == "s":
                if argument is None or argument.string is None:
                    return None
                rendered = len(argument.string.encode("utf-8"))
                if precision is not None:
                    rendered = min(rendered, precision)
            elif conversion in "di":
                rendered = 20 if length in {"l", "ll", "j", "z", "t"} else 11
            elif conversion in "ouxX":
                rendered = 20 if length in {"l", "ll", "j", "z", "t"} else 10
            elif conversion == "p":
                rendered = 18
            elif conversion == "c":
                rendered = 1
            elif conversion in "fF":
                # Fixed notation can expand a finite double to hundreds of
                # digits; account for that unless a wider field already does.
                rendered = 324 + (precision if precision is not None else 6)
            elif conversion in "eE":
                rendered = (precision if precision is not None else 6) + 8
            elif conversion in "gG":
                # %g chooses the shorter of fixed/scientific notation.  For
                # an IEEE-754 double, sign + significant digits + decimal +
                # e/sign/three-digit exponent is a conservative finite bound.
                rendered = (precision if precision is not None else 6) + 7
            else:
                # Hex-float: sign, 0x, radix point, exponent marker/sign and a
                # four-digit exponent comfortably cover binary64 output.
                rendered = (precision if precision is not None else 13) + 10
            total += max(width, rendered)
        total += len(text[cursor:].encode("utf-8"))
        # An unsupported '%' directive means the estimate is incomplete.
        if "%" in pattern.sub("", text).replace("%%", ""):
            return None
        return total

    def _check_bounded(
        self,
        function: FunctionIR,
        call: Call,
        tainted: _TaintState,
        buffers: dict[str, BufferInfo],
    ) -> list[Finding]:
        name = normalize_symbol(call.name)
        source_index: int | None = None
        if name in COPY_SPECS:
            destination_index, source_index, length_indexes = COPY_SPECS[name]
        elif name in BOUNDED_WRITE_SPECS:
            destination_index, length_indexes = BOUNDED_WRITE_SPECS[name]
        elif name in BOUNDED_READ_SPECS:
            source_index, length_indexes = BOUNDED_READ_SPECS[name]
            source = self._arg(call, source_index)
            length_parts = [self._arg(call, index) for index in length_indexes]
            if source is None or any(part is None for part in length_parts):
                return []
            parts = [part for part in length_parts if part is not None]
            bounds = self._check_source_bounds(
                function,
                call,
                source,
                parts,
                buffers,
            )
            if bounds:
                return bounds
            if name in {"memchr", "memrchr"}:
                # A bounded search returns only a pointer/NULL; unlike write,
                # send, or fwrite it does not disclose the bytes it examines.
                return []
            return self._check_uninitialized_source_tail(
                function, call, source, parts, buffers
            )
        elif name in BOUNDED_MULTI_READ_SPECS:
            source_indexes, length_indexes = BOUNDED_MULTI_READ_SPECS[name]
            length_parts = [self._arg(call, index) for index in length_indexes]
            if any(part is None for part in length_parts):
                return []
            parts = [part for part in length_parts if part is not None]
            findings: list[Finding] = []
            for index in source_indexes:
                source = self._arg(call, index)
                if source is not None:
                    findings.extend(
                        self._check_source_bounds(
                            function, call, source, parts, buffers
                        )
                    )
            return findings
        else:
            return []

        destination = self._arg(call, destination_index)
        length_parts = [self._arg(call, index) for index in length_indexes]
        if destination is None or any(part is None for part in length_parts):
            return []
        parts = [part for part in length_parts if part is not None]
        findings: list[Finding] = []
        fortify_capacity = self._active_fortify_capacity(call, tainted)
        if fortify_capacity is not None:
            length_value = self._product_value(parts)
            capacity_value = self._eval_int(fortify_capacity)
            if (
                length_value is not None
                and capacity_value is not None
                and length_value > capacity_value
            ):
                # The fortify wrapper aborts before touching either object.
                return []
        if source_index is not None:
            source = self._arg(call, source_index)
            if source is not None:
                findings.extend(
                    self._check_source_bounds(
                        function, call, source, parts, buffers
                    )
                )
        if fortify_capacity is not None:
            return findings

        buffer = self._buffer_for(destination, buffers)
        if buffer is None:
            findings.extend(
                self._check_record_size_overflow(
                    function, call, destination, parts
                )
            )
            findings.extend(
                self._check_dynamic_allocation_overflow(
                    function, call, destination, parts
                )
            )
            return findings

        capacity = self._available_capacity(destination, buffer)
        length_value = self._product_value(parts)
        length_text = " * ".join(part.text or "?" for part in parts)
        if (
            destination.offset < 0
            and buffer.precise
            and length_value is not None
            and length_value > 0
        ):
            findings.append(
                self._finding(
                    function,
                    call,
                    "BUF-003",
                    f"{buffer.storage.title()} buffer overflow",
                    Severity.CRITICAL,
                    "High",
                    f"{name} starts before the destination object",
                    (
                        f"start_offset={destination.offset}; "
                        f"length={length_value}; "
                        f"destination={destination.text or destination.key}"
                    ),
                )
            )
            return findings
        length_tainted = any(self._is_tainted(part, tainted) for part in parts)
        guarded_upper = self._guarded_length_product_upper_bound(
            function, call, parts
        )

        if capacity is None:
            findings.extend(
                self._check_dynamic_allocation_overflow(
                    function, call, destination, parts
                )
            )

        if capacity is not None and length_value is not None:
            if name == "strncat":
                unsafe = length_value >= capacity
            else:
                unsafe = length_value > capacity
            if not unsafe:
                return findings
            if not buffer.precise and (
                buffer.physical_capacity is None
                or buffer.physical_capacity <= (buffer.capacity or 0)
            ):
                # A scalar passed by address or a decompiler-split stack lvar
                # does not establish the end of the underlying object.  A
                # constant comparison against that fragment is therefore not
                # proof of an overwrite.
                return findings
            physical_capacity = self._available_physical_capacity(
                destination, buffer
            )
            if (
                buffer.storage == "stack"
                and physical_capacity is not None
                and length_value <= physical_capacity
            ):
                # The type is a split lvar, but the requested write remains in
                # the compiler-allocated stack span.  This is common for
                # protocol packets and large response buffers.
                return findings
            findings.append(
                self._finding(
                    function,
                    call,
                    "BUF-003",
                    f"{buffer.storage.title()} buffer overflow",
                    Severity.CRITICAL,
                    "High",
                    f"{name} bound exceeds destination capacity",
                    f"length={length_value}; "
                    f"{self._destination_evidence(destination, capacity)}",
                )
            )
            return findings

        semantic_copy_fallback = bool(
            name == "memcpy_like"
            and buffer.storage == "stack"
            and buffer.precise
            and capacity is not None
            and (
                buffer.physical_capacity is None
                or buffer.physical_capacity <= buffer.capacity
            )
            and not self._copy_length_has_capacity_guard(
                function, call, parts, capacity
            )
        )
        if capacity is None:
            return findings
        if guarded_upper is not None and guarded_upper <= capacity:
            return findings
        physical_capacity = self._available_physical_capacity(
            destination, buffer
        )
        if (
            buffer.storage == "stack"
            and guarded_upper is not None
            and physical_capacity is not None
            and guarded_upper <= physical_capacity
        ):
            return findings
        if not buffer.precise and (
            physical_capacity is None
            or physical_capacity <= (buffer.capacity or 0)
        ):
            return findings
        insufficient_guard = bool(
            guarded_upper is not None and guarded_upper > capacity
        )
        if not length_tainted and not semantic_copy_fallback and not insufficient_guard:
            return findings

        if name == "strncat":
            summary = "strncat bound ignores the existing destination length"
            severity = Severity.HIGH if length_tainted else Severity.MEDIUM
        elif length_tainted:
            summary = f"attacker-influenced length reaches {name}"
            severity = Severity.HIGH
        elif insufficient_guard:
            summary = f"visible length bound still exceeds {name} destination"
            severity = Severity.HIGH
        else:
            summary = f"unresolved length reaches fixed-size destination in {name}"
            severity = Severity.MEDIUM

        findings.append(
            self._finding(
                function,
                call,
                "BUF-004",
                f"{buffer.storage.title()} buffer overflow",
                severity,
                "Medium",
                summary,
                (
                    f"length={length_text}; "
                    + (
                        f"visible_upper_bound={guarded_upper}; "
                        if guarded_upper is not None
                        else ""
                    )
                    + self._destination_evidence(destination, capacity)
                ),
            )
        )
        return findings

    def _active_fortify_capacity(
        self, call: Call, tainted: _TaintState
    ) -> Expr | None:
        """Return a trusted active destination-size check, if present."""

        index = FORTIFIED_DESTINATION_SPECS.get(normalize_symbol(call.name))
        capacity = self._arg(call, index)
        return self._trusted_fortify_capacity(capacity, tainted)

    def _trusted_fortify_capacity(
        self, capacity: Expr | None, tainted: _TaintState
    ) -> Expr | None:
        """Validate one compiler-supplied object-size expression."""

        if capacity is None or self._is_tainted(capacity, tainted):
            return None
        concrete = self._eval_int(capacity)
        if concrete is None:
            return capacity
        if concrete < 0:
            return None
        bits = capacity.bits
        if bits is not None and bits > 0 and concrete == (1 << bits) - 1:
            return None
        return capacity

    def _fortify_call_must_abort(
        self, call: Call, tainted: _TaintState
    ) -> bool:
        """Return whether a bounded fortify call provably fails before I/O.

        The object-size argument alone only proves that an overflow will be
        stopped.  It makes subsequent code unreachable only when both the
        requested byte count and the trusted capacity are concrete and the
        request is strictly larger.
        """

        capacity = self._active_fortify_capacity(call, tainted)
        if capacity is None:
            return False
        name = normalize_symbol(call.name)
        if name in COPY_SPECS:
            length_indexes = COPY_SPECS[name][2]
        elif name in BOUNDED_WRITE_SPECS:
            length_indexes = BOUNDED_WRITE_SPECS[name][1]
        else:
            return False
        lengths = [self._arg(call, index) for index in length_indexes]
        if any(length is None for length in lengths):
            return False
        requested = self._product_value(
            [length for length in lengths if length is not None]
        )
        available = self._eval_int(capacity)
        return bool(
            requested is not None
            and available is not None
            and requested > available
        )

    def _infer_record_capacity_roots(
        self, functions: list[FunctionIR]
    ) -> frozenset[str]:
        """Find global record tables that store ``{size, allocated_ptr}``.

        Optimized menu binaries often turn a record array into pointer
        arithmetic through a local base variable.  Tracking the global root,
        rather than relying on Hex-Rays to retain a field key, lets later
        actions relate the sibling size and pointer fields across functions.
        """

        result: set[str] = set()
        for function in functions:
            assignments = [
                statement
                for statement in function.statements
                if isinstance(statement, Assignment)
            ]
            for allocation in assignments:
                size_parts = self._allocation_size_parts(allocation.value)
                if size_parts is None:
                    continue
                roots = self._expression_global_roots(
                    function, allocation.target, allocation
                )
                if not roots:
                    continue
                size_keys = set().union(
                    *(part.dependencies() for part in size_parts)
                )
                size_keys = self._related_assignment_keys(function, size_keys)
                if not size_keys:
                    continue
                for sibling in assignments:
                    if sibling is allocation:
                        continue
                    if not (sibling.value.dependencies() & size_keys):
                        continue
                    sibling_roots = self._expression_global_roots(
                        function, sibling.target, sibling
                    )
                    result.update(roots & sibling_roots)
        return frozenset(result)

    @staticmethod
    def _infer_custom_release_arguments(
        functions: list[FunctionIR],
    ) -> dict[int, frozenset[int]]:
        """Recognize allocator release primitives without relying on symbols.

        A pool release commonly aligns its object argument to an owning page,
        returns small objects to a freelist by writing through the object, and
        unmaps the derived page for large objects.  Requiring both destructive
        signatures avoids treating ordinary munmap/lookup helpers as frees.
        The result is deliberately scoped to retained-global checks instead of
        becoming a general lifetime summary for allocator internals.
        """

        releases: dict[int, frozenset[int]] = {}
        for function in functions:
            if not function.parameters:
                continue
            origins: dict[str, set[int]] = {
                key: {index} for index, key in enumerate(function.parameters)
            }
            assignments = [
                statement
                for statement in function.statements
                if isinstance(statement, Assignment)
                and statement.target.kind == "var"
                and statement.target.key
            ]
            for _ in range(max(2, len(assignments) + 1)):
                changed = False
                for assignment in assignments:
                    value = assignment.value.unwrapped()
                    dependencies = value.dependencies()
                    inherited: set[int] = set()
                    if value.kind not in {"call", "deref", "member", "index"}:
                        for dependency in dependencies:
                            inherited.update(origins.get(dependency, ()))
                    target = assignment.target.key
                    merged = origins.get(target, set()) | inherited
                    if merged != origins.get(target, set()):
                        origins[target] = merged
                        changed = True
                if not changed:
                    break

            def parameter_origins(expression: Expr) -> set[int]:
                result: set[int] = set()
                for dependency in expression.dependencies():
                    result.update(origins.get(dependency, ()))
                return result

            unmapped: set[int] = set()
            overwritten: set[int] = set()
            for statement in function.statements:
                if isinstance(statement, Call):
                    if normalize_symbol(statement.name) == "munmap" and statement.args:
                        unmapped.update(parameter_origins(statement.args[0]))
                    continue
                if not isinstance(statement, Assignment):
                    continue
                target = statement.target.unwrapped()
                if target.kind in {"deref", "member", "index"}:
                    overwritten.update(parameter_origins(target))
            detected = unmapped & overwritten
            if detected:
                releases[function.ea] = frozenset(detected)
        return releases

    def _expression_global_roots(
        self,
        function: FunctionIR,
        expression: Expr,
        before: Assignment | Call,
    ) -> set[str]:
        """Resolve global provenance through reaching local assignments."""

        position = lambda item: (item.ea, item.order)
        assignments = [
            statement
            for statement in function.statements
            if isinstance(statement, Assignment)
            and statement.target.kind == "var"
            and statement.target.key
        ]

        def visit(value: Expr, limit: tuple[int, int], seen: set[str]) -> set[str]:
            dependencies = value.dependencies()
            roots = {key for key in dependencies if key.startswith("g:")}
            for dependency in dependencies:
                if dependency.startswith("g:") or dependency in seen:
                    continue
                reaching = [
                    statement
                    for statement in assignments
                    if statement.target.key == dependency
                    and position(statement) < limit
                ]
                if not reaching:
                    continue
                origin = max(reaching, key=position)
                roots.update(
                    visit(origin.value, position(origin), seen | {dependency})
                )
            return roots

        return visit(expression, position(before), set())

    def _check_record_size_overflow(
        self,
        function: FunctionIR,
        call: Call,
        destination: Expr,
        lengths: list[Expr],
    ) -> list[Finding]:
        """Detect a stored allocation size enlarged at a sibling pointer sink."""

        if len(lengths) != 1 or not self.record_capacity_roots:
            return []
        length = lengths[0]
        destination_roots = {
            key
            for key in destination.dependencies()
            if key in self.record_capacity_roots
        }
        length_roots = {
            key for key in length.dependencies() if key in self.record_capacity_roots
        }
        common_roots = destination_roots & length_roots
        if not common_roots:
            return []

        # Require a shared record selector as well as the same table.  This
        # avoids connecting unrelated entries in one global arena.
        destination_selectors = {
            key
            for key in destination.dependencies()
            if not key.startswith("g:")
        }
        length_selectors = {
            key for key in length.dependencies() if not key.startswith("g:")
        }
        if not (destination_selectors & length_selectors):
            return []

        extra = self._positive_record_size_increment(length, common_roots)
        if extra is None:
            return []
        root = min(common_roots)
        return [
            self._finding(
                function,
                call,
                "BUF-010",
                "Heap buffer overflow",
                Severity.CRITICAL,
                "Medium",
                f"stored allocation size is enlarged before {normalize_symbol(call.name)}",
                (
                    f"record={root}; positive_increment={extra}; "
                    f"length={length.text or '<expression>'}; "
                    f"destination={destination.text or '<expression>'}"
                ),
            )
        ]

    def _check_dynamic_allocation_overflow(
        self,
        function: FunctionIR,
        call: Call,
        destination: Expr,
        lengths: list[Expr],
    ) -> list[Finding]:
        """Prove an additive overrun relative to a symbolic allocation size.

        Constant capacities are handled by BUF-003.  This rule covers the
        equally deterministic symbolic case, such as ``p = malloc(n)``
        followed by ``read(fd, p, n + 1)``.  It deliberately requires one
        reaching allocation definition and identical affine dynamic terms;
        inequalities between unrelated symbolic expressions are not guessed.
        """

        name = normalize_symbol(call.name)
        if (
            name == "strncat"
            or not lengths
            or destination.key is None
            or not self._is_buffer_alias_expression(destination, destination.key)
        ):
            return []
        proof = self._symbolic_allocation_excess(
            function, call, destination, lengths
        )
        if proof is None:
            return []
        allocator, allocation_text, write_text, total_offset, excess = proof
        return [
            self._finding(
                function,
                call,
                "BUF-012",
                "Heap buffer overflow",
                Severity.CRITICAL,
                "High",
                f"symbolic write bound exceeds {allocator or 'heap'} allocation",
                (
                    f"allocator={allocator or '<wrapper>'}; "
                    f"allocation={allocation_text}; write={write_text}; "
                    f"destination_offset={total_offset}; "
                    f"guaranteed_excess={excess}"
                ),
            )
        ]

    def _check_dynamic_allocation_overread(
        self,
        function: FunctionIR,
        call: Call,
        source: Expr,
        lengths: list[Expr],
    ) -> list[Finding]:
        """Prove a symbolic byte range extends past its source allocation."""

        proof = self._symbolic_allocation_excess(
            function, call, source, lengths
        )
        if proof is None:
            return []
        allocator, allocation_text, read_text, total_offset, excess = proof
        return [
            self._finding(
                function,
                call,
                "BUF-013",
                "Out-of-bounds read",
                Severity.HIGH,
                "High",
                (
                    "symbolic source range exceeds allocation in "
                    f"{normalize_symbol(call.name)}"
                ),
                (
                    f"allocator={allocator or '<wrapper>'}; "
                    f"allocation={allocation_text}; read={read_text}; "
                    f"source_offset={total_offset}; guaranteed_excess={excess}"
                ),
            )
        ]

    def _symbolic_allocation_excess(
        self,
        function: FunctionIR,
        call: Call,
        value: Expr,
        lengths: list[Expr],
    ) -> tuple[str | None, str, str, int, int] | None:
        """Return a strict affine excess over one reaching heap allocation."""

        if (
            not lengths
            or value.key is None
            or not self._is_buffer_alias_expression(value, value.key)
        ):
            return None
        allocation = self._reaching_dynamic_allocation(
            function, call, value.key
        )
        if allocation is None:
            return None
        assignment, allocation_parts, allocator, alias_offset = allocation
        # mmap grants page-rounded storage, so requested_size + 1 is not proof
        # of an overrun unless the rounded mapping size is also known.
        if allocator in {"mmap", "mmap64"}:
            return None

        allocation_form = self._affine_product(allocation_parts)
        access_form = self._affine_product(lengths)
        if allocation_form is None or access_form is None:
            return None
        allocation_terms, allocation_constant = allocation_form
        access_terms, access_constant = access_form
        total_offset = alias_offset + value.offset
        access_constant += max(0, total_offset)
        if (
            not allocation_terms
            or allocation_terms != access_terms
            or access_constant <= allocation_constant
        ):
            return None

        dependencies = set().union(
            *(part.dependencies() for part in allocation_parts)
        )
        if self._dependencies_may_change_between(
            function, assignment, call, dependencies
        ):
            return None

        allocation_text = " * ".join(
            part.text or "?" for part in allocation_parts
        )
        access_text = " * ".join(part.text or "?" for part in lengths)
        return (
            allocator,
            allocation_text,
            access_text,
            total_offset,
            access_constant - allocation_constant,
        )

    def _reaching_dynamic_allocation(
        self,
        function: FunctionIR,
        before: Call | Assignment,
        key: str,
        seen: frozenset[int] = frozenset(),
    ) -> tuple[Assignment, list[Expr], str | None, int] | None:
        """Resolve a unique reaching allocation through pointer-only aliases."""

        reaching = self._unique_reaching_assignment(function, before, key)
        if reaching is None or id(reaching) in seen:
            return None
        value = reaching.value.unwrapped()
        size_parts = self._allocation_size_parts(value)
        if size_parts is not None:
            return reaching, size_parts, self._allocation_name(value), 0
        if (
            value.key is None
            or not self._is_buffer_alias_expression(value, value.key)
        ):
            return None
        origin = self._reaching_dynamic_allocation(
            function,
            reaching,
            value.key,
            seen | {id(reaching)},
        )
        if origin is None:
            return None
        assignment, parts, allocator, offset = origin
        return assignment, parts, allocator, offset + value.offset

    @staticmethod
    def _unique_reaching_assignment(
        function: FunctionIR,
        before: Call | Assignment,
        key: str,
    ) -> Assignment | None:
        """Return the sole definition of ``key`` reaching ``before``.

        With CFG data this is a small reaching-definitions analysis.  A local
        definition before the sink kills every incoming value; otherwise all
        predecessor definitions must converge to exactly one assignment.
        """

        assignments = [
            statement
            for statement in function.statements
            if isinstance(statement, Assignment)
            and statement.target.kind in {"var", "global"}
            and statement.target.offset == 0
            and statement.target.key == key
        ]
        if not assignments:
            return None
        if (
            not function.blocks
            or function.entry_block is None
            or before.block_id not in function.blocks
        ):
            prior = [item for item in assignments if item.order < before.order]
            return max(prior, key=lambda item: item.order) if prior else None

        # Missing block provenance makes branch-sensitive resolution unsafe.
        if any(item.block_id not in function.blocks for item in assignments):
            return None
        local = [
            item
            for item in assignments
            if item.block_id == before.block_id and item.order < before.order
        ]
        if local:
            return max(local, key=lambda item: item.order)

        indexed = list(enumerate(assignments))
        generated: dict[int, int] = {}
        for block_id in function.blocks:
            candidates = [
                (index, item)
                for index, item in indexed
                if item.block_id == block_id
            ]
            if candidates:
                generated[block_id] = max(
                    candidates, key=lambda pair: pair[1].order
                )[0]

        incoming = {block_id: set() for block_id in function.blocks}
        outgoing = {block_id: set() for block_id in function.blocks}
        undefined = -1
        changed = True
        while changed:
            changed = False
            for block_id, block in function.blocks.items():
                if block_id == function.entry_block:
                    updated_in = {undefined}
                else:
                    predecessor_values = [
                        outgoing[pred]
                        for pred in block.predecessors
                        if pred in outgoing
                    ]
                    updated_in = (
                        set().union(*predecessor_values)
                        if predecessor_values
                        else {undefined}
                    )
                updated_out = (
                    {generated[block_id]}
                    if block_id in generated
                    else set(updated_in)
                )
                if (
                    updated_in != incoming[block_id]
                    or updated_out != outgoing[block_id]
                ):
                    incoming[block_id] = updated_in
                    outgoing[block_id] = updated_out
                    changed = True

        reaching = incoming[before.block_id]
        if len(reaching) != 1 or undefined in reaching:
            return None
        return assignments[next(iter(reaching))]

    @classmethod
    def _affine_product(
        cls, expressions: list[Expr]
    ) -> tuple[dict[object, int], int] | None:
        """Normalize a product into affine coefficients plus a constant."""

        if not expressions:
            return None
        constant_factor = 1
        dynamic: list[Expr] = []
        for expression in expressions:
            value = cls._eval_int(expression)
            if value is None:
                dynamic.append(expression)
            else:
                constant_factor *= value
        if not dynamic:
            return {}, constant_factor
        if len(dynamic) == 1:
            form = cls._affine_form(dynamic[0])
            if form is None:
                return None
            terms, constant = form
            return (
                {
                    atom: coefficient * constant_factor
                    for atom, coefficient in terms.items()
                    if coefficient * constant_factor
                },
                constant * constant_factor,
            )
        atom = cls._affine_product_atom(dynamic)
        return ({atom: constant_factor} if constant_factor else {}, 0)

    @classmethod
    def _affine_form(
        cls, expression: Expr
    ) -> tuple[dict[object, int], int] | None:
        concrete = cls._eval_int(expression)
        if concrete is not None:
            return {}, concrete
        value = expression.unwrapped()
        if value.kind == "op" and value.op in {"add", "sub"} and value.children:
            forms = [cls._affine_form(child) for child in value.children]
            if any(form is None for form in forms):
                return None
            terms: dict[object, int] = {}
            constant = 0
            for index, form in enumerate(forms):
                if form is None:
                    continue
                child_terms, child_constant = form
                sign = -1 if value.op == "sub" and index else 1
                constant += sign * child_constant
                for atom, coefficient in child_terms.items():
                    terms[atom] = terms.get(atom, 0) + sign * coefficient
            return (
                {
                    atom: coefficient
                    for atom, coefficient in terms.items()
                    if coefficient
                },
                constant,
            )
        if value.kind == "op" and value.op == "mul" and value.children:
            return cls._affine_product(list(value.children))
        if value.kind == "op" and value.op == "shl" and len(value.children) == 2:
            shift = cls._eval_int(value.children[1])
            if shift is None or shift < 0:
                return None
            form = cls._affine_form(value.children[0])
            if form is None:
                return None
            terms, constant = form
            factor = 1 << shift
            return (
                {atom: coefficient * factor for atom, coefficient in terms.items()},
                constant * factor,
            )
        return {cls._expression_signature(value): 1}, 0

    @classmethod
    def _affine_product_atom(cls, expressions: list[Expr]) -> object:
        return (
            "product",
            tuple(
                sorted(
                    (cls._expression_signature(item) for item in expressions),
                    key=repr,
                )
            ),
        )

    @classmethod
    def _dependencies_may_change_between(
        cls,
        function: FunctionIR,
        start: Assignment,
        end: Call | Assignment,
        dependencies: set[str],
    ) -> bool:
        if not dependencies:
            return False
        writes = [
            statement
            for statement in function.statements
            if isinstance(statement, Assignment)
            and statement is not start
            and statement.target.kind in {"var", "global"}
            and statement.target.offset == 0
            and statement.target.key in dependencies
        ]
        if (
            not function.blocks
            or start.block_id not in function.blocks
            or end.block_id not in function.blocks
        ):
            return any(start.order < item.order < end.order for item in writes)

        for item in writes:
            if item.block_id not in function.blocks:
                return True
            if start.block_id == end.block_id:
                if (
                    item.block_id == start.block_id
                    and start.order < item.order < end.order
                ):
                    return True
                continue
            if item.block_id == start.block_id:
                if item.order > start.order:
                    return True
                continue
            if item.block_id == end.block_id:
                if item.order < end.order:
                    return True
                continue
            if cls._block_reaches(
                function, start.block_id, item.block_id
            ) and cls._block_reaches(function, item.block_id, end.block_id):
                return True
        return False

    @classmethod
    def _positive_record_size_increment(
        cls, expression: Expr, roots: set[str]
    ) -> int | None:
        value = expression.unwrapped()
        if value.op == "add" and len(value.children) == 2:
            for constant, dynamic in (
                (value.children[0], value.children[1]),
                (value.children[1], value.children[0]),
            ):
                if (
                    constant.kind == "const"
                    and constant.value is not None
                    and constant.value > 0
                    and dynamic.dependencies() & roots
                    and any(
                        node.kind in {"deref", "member", "index"}
                        for node in cls._walk_expression(dynamic)
                    )
                ):
                    return constant.value
        return None

    @classmethod
    def _guarded_upper_bound(
        cls, function: FunctionIR, call: Call, lengths: list[Expr]
    ) -> int | None:
        """Return the tightest literal upper bound attached to a sink call."""

        keys = set().union(*(part.dependencies() for part in lengths))
        return cls._path_literal_upper_bound(function, call, keys)

    @classmethod
    def _guarded_length_product_upper_bound(
        cls, function: FunctionIR, call: Call, lengths: list[Expr]
    ) -> int | None:
        """Return a path upper bound for a byte-count product.

        A single literal guard can bound ``write(..., count)`` directly. APIs
        such as ``fread`` and ``fwrite`` instead consume ``size * count``;
        taking the tightest bound across both operands is unsound. Resolve
        every factor independently, preserve exact zero factors, and multiply
        only when all factors have a nonnegative concrete or guarded bound.
        """

        if not lengths:
            return None
        upper = 1
        for part in lengths:
            factor = cls._eval_int(part)
            if factor is None:
                factor = cls._guarded_upper_bound(function, call, [part])
            if factor is None or factor < 0:
                return None
            upper *= factor
        return upper

    @classmethod
    def _path_literal_upper_bound(
        cls,
        function: FunctionIR,
        statement: Call | Assignment | Return,
        keys: set[str],
    ) -> int | None:
        """Return an upper bound implied by the statement's proven path."""

        if not keys:
            return None
        bounds: list[int] = []
        for guarded_expression in cls._path_guard_expressions(function, statement):
            for comparison in cls._conjunctive_comparison_leaves(
                guarded_expression
            ):
                if len(comparison.children) != 2:
                    continue
                left, right = comparison.children
                left_matches = cls._value_matches_keys(left, keys)
                right_matches = cls._value_matches_keys(right, keys)
                if left_matches == right_matches:
                    continue
                constant = right if left_matches else left
                if constant.kind != "const" or constant.value is None:
                    continue
                op = comparison.op
                if left_matches and op in {"sle", "ule", "eq"}:
                    bounds.append(constant.value)
                elif left_matches and op in {"slt", "ult"}:
                    bounds.append(constant.value - 1)
                elif right_matches and op in {"sge", "uge", "eq"}:
                    bounds.append(constant.value)
                elif right_matches and op in {"sgt", "ugt"}:
                    bounds.append(constant.value - 1)
        return min(bounds) if bounds else None

    @classmethod
    def _path_literal_integer_bounds(
        cls,
        function: FunctionIR,
        statement: Call | Assignment | Return,
        keys: set[str],
        signed: bool | None,
    ) -> tuple[int | None, int | None]:
        """Return literal bounds in the expression's arithmetic domain.

        A signed comparison on an unsigned value (or the reverse) does not
        establish a range in the value's domain. This distinction matters for
        size arithmetic because a casted guard can otherwise hide wraparound.
        """

        if not keys:
            return None, None
        lower_bounds: list[int] = []
        upper_bounds: list[int] = []
        reverse = {
            "slt": "sgt",
            "ult": "ugt",
            "sle": "sge",
            "ule": "uge",
            "sgt": "slt",
            "ugt": "ult",
            "sge": "sle",
            "uge": "ule",
        }
        for guarded_expression in cls._path_guard_expressions(function, statement):
            for comparison in cls._conjunctive_comparison_leaves(
                guarded_expression
            ):
                if len(comparison.children) != 2:
                    continue
                left, right = comparison.children
                left_matches = cls._value_matches_keys(left, keys)
                right_matches = cls._value_matches_keys(right, keys)
                if left_matches == right_matches:
                    continue
                constant = right if left_matches else left
                if constant.kind != "const" or constant.value is None:
                    continue
                op = comparison.op or ""
                if right_matches:
                    op = reverse.get(op, op)
                if op != "eq":
                    if signed is True and not op.startswith("s"):
                        continue
                    if signed is False and not op.startswith("u"):
                        continue
                    if signed is None:
                        continue
                if op == "eq":
                    lower_bounds.append(constant.value)
                    upper_bounds.append(constant.value)
                elif op in {"sge", "uge"}:
                    lower_bounds.append(constant.value)
                elif op in {"sgt", "ugt"}:
                    lower_bounds.append(constant.value + 1)
                elif op in {"sle", "ule"}:
                    upper_bounds.append(constant.value)
                elif op in {"slt", "ult"}:
                    upper_bounds.append(constant.value - 1)
        return (
            max(lower_bounds) if lower_bounds else None,
            min(upper_bounds) if upper_bounds else None,
        )

    def _copy_length_has_capacity_guard(
        self,
        function: FunctionIR,
        call: Call,
        lengths: list[Expr],
        capacity: int,
    ) -> bool:
        """Find a visible positive upper-bound check for a dynamic copy size."""

        upper = self._guarded_upper_bound(function, call, lengths)
        return upper is not None and 0 <= upper <= capacity

    def _check_scanf(
        self,
        function: FunctionIR,
        call: Call,
        buffers: dict[str, BufferInfo],
    ) -> list[Finding]:
        name = normalize_symbol(call.name)
        spec = SCANF_SPECS.get(name)
        if spec is None:
            return []
        format_index, first_output, _ = spec
        format_expression = self._arg(call, format_index)
        if format_expression is None or format_expression.string is None:
            return []

        findings: list[Finding] = []
        output_index = first_output
        for match in _SCANF_CONVERSION.finditer(format_expression.string):
            if match.group("suppress"):
                continue
            argument = self._arg(call, output_index)
            output_index += 1
            if argument is None:
                break
            buffer = self._buffer_for(argument, buffers)
            raw_conversion = match.group("conversion")
            conversion = "[" if raw_conversion.startswith("[") else raw_conversion
            if conversion not in {"s", "c", "["} or buffer is None:
                continue

            width_text = match.group("width")
            width = int(width_text) if width_text else None
            capacity = self._available_capacity(argument, buffer)
            unbounded = width is None and conversion in {"s", "["}
            required = None
            if width is not None:
                required = width + (1 if conversion in {"s", "["} else 0)
            elif conversion == "c":
                required = 1

            if not unbounded and (
                required is None or capacity is None or required <= capacity
            ):
                continue

            physical_capacity = self._available_physical_capacity(argument, buffer)
            if (
                not unbounded
                and required is not None
                and buffer.storage == "stack"
                and physical_capacity is not None
                and required <= physical_capacity
            ):
                continue

            if unbounded:
                summary = f"%{conversion} conversion has no field width"
                severity = Severity.HIGH
                evidence = self._destination_evidence(argument, capacity)
            else:
                summary = "scanf field width exceeds destination capacity"
                severity = Severity.CRITICAL
                evidence = (
                    f"conversion requires {required} bytes; "
                    f"{self._destination_evidence(argument, capacity)}"
                )
            findings.append(
                self._finding(
                    function,
                    call,
                    "BUF-005",
                    f"{buffer.storage.title()} buffer overflow",
                    severity,
                    "High",
                    summary,
                    evidence,
                )
            )
        return findings

    def _check_source_bounds(
        self,
        function: FunctionIR,
        call: Call,
        source: Expr,
        length_parts: list[Expr],
        buffers: dict[str, BufferInfo],
    ) -> list[Finding]:
        """Check byte ranges read by copy and bounded-output operations.

        Destination-only checking misses a common CTF pattern where a JSON or
        protocol length is larger than the allocation that supplied the source
        bytes.  Concrete precise capacities and same-function symbolic heap
        allocations are accepted; unknown pointer parameters remain silent
        until a caller read summary provides one.
        """

        if source.string is not None:
            # String literals occupy their encoded bytes plus the compiler-
            # supplied trailing NUL. strncpy/strncat can stop at that NUL and
            # therefore do not consume their complete nominal count.
            if normalize_symbol(call.name) in {
                "strncpy",
                "__strncpy_chk",
                "strncat",
            }:
                return []
            capacity = len(source.string.encode("utf-8")) + 1
            length_value = self._product_value(length_parts)
            if length_value is not None:
                if length_value <= capacity:
                    return []
                return [
                    self._finding(
                        function,
                        call,
                        "BUF-007",
                        "Out-of-bounds read",
                        Severity.HIGH,
                        "High",
                        (
                            f"{normalize_symbol(call.name)} reads past "
                            "the source literal"
                        ),
                        (
                            f"length={length_value}; source={source.text}; "
                            f"available_source_capacity={capacity}"
                        ),
                    )
                ]
            guarded_upper = self._guarded_length_product_upper_bound(
                function, call, length_parts
            )
            if guarded_upper is None or guarded_upper <= capacity:
                return []
            return [
                self._finding(
                    function,
                    call,
                    "BUF-007",
                    "Out-of-bounds read",
                    Severity.HIGH,
                    "Medium",
                    (
                        "visible length bound still exceeds "
                        f"{normalize_symbol(call.name)} source literal"
                    ),
                    (
                        f"visible_upper_bound={guarded_upper}; "
                        f"source={source.text}; "
                        f"available_source_capacity={capacity}"
                    ),
                )
            ]

        buffer = self._buffer_for(source, buffers)
        if buffer is None or buffer.capacity is None:
            symbolic = self._check_dynamic_allocation_overread(
                function, call, source, length_parts
            )
            if symbolic:
                return symbolic
        if buffer is None or buffer.capacity is None or not buffer.precise:
            return []
        length_value = self._product_value(length_parts)
        if source.offset < 0 and length_value is not None:
            if length_value <= 0:
                return []
            return [
                self._finding(
                    function,
                    call,
                    "BUF-007",
                    "Out-of-bounds read",
                    Severity.HIGH,
                    "High",
                    (
                        f"{normalize_symbol(call.name)} reads before "
                        "the source object"
                    ),
                    (
                        f"start_offset={source.offset}; length={length_value}; "
                        f"source={source.text or source.key}"
                    ),
                )
            ]
        capacity = self._available_capacity(source, buffer)
        if capacity is None:
            return []
        physical_capacity = self._available_physical_capacity(source, buffer)
        capacity_evidence = f"available_source_capacity={capacity}"
        if (
            physical_capacity is not None
            and physical_capacity != capacity
        ):
            capacity_evidence += (
                f"; available_physical_capacity={physical_capacity}"
            )
        if length_value is not None:
            if length_value <= capacity:
                return []
            if (
                buffer.storage == "stack"
                and physical_capacity is not None
                and length_value <= physical_capacity
            ):
                return []
            return [
                self._finding(
                    function,
                    call,
                    "BUF-007",
                    "Out-of-bounds read",
                    Severity.HIGH,
                    "High",
                    f"{normalize_symbol(call.name)} reads past the source object",
                    (
                        f"length={length_value}; source={source.text or source.key}; "
                        f"{capacity_evidence}"
                    ),
                )
            ]

        guarded_upper = self._guarded_length_product_upper_bound(
            function, call, length_parts
        )
        if guarded_upper is None or guarded_upper <= capacity:
            return []
        if (
            buffer.storage == "stack"
            and physical_capacity is not None
            and guarded_upper <= physical_capacity
        ):
            return []
        length_text = " * ".join(part.text or "?" for part in length_parts)
        return [
            self._finding(
                function,
                call,
                "BUF-007",
                "Out-of-bounds read",
                Severity.HIGH,
                "Medium",
                (
                    "visible length bound still exceeds "
                    f"{normalize_symbol(call.name)} source object"
                ),
                (
                    f"length={length_text}; visible_upper_bound={guarded_upper}; "
                    f"source={source.text or source.key}; "
                    f"{capacity_evidence}"
                ),
            )
        ]

    def _check_summary_reads(
        self,
        function: FunctionIR,
        call: Call,
        tainted: _TaintState,
        buffers: dict[str, BufferInfo],
    ) -> list[Finding]:
        if self._has_direct_call_model(normalize_symbol(call.name)):
            return []
        summary = self._summary_for_call(call)
        if summary is None:
            return []
        findings: list[Finding] = []
        for effect in summary.reads:
            source = effect.source.resolve(call.args)
            lengths = tuple(
                value
                for ref in effect.lengths
                if (value := ref.resolve(call.args)) is not None
            )
            if source is None or len(lengths) != len(effect.lengths):
                continue
            fortify_capacity = (
                effect.fortify_capacity.resolve(call.args)
                if effect.fortify_capacity is not None
                else None
            )
            active_capacity = self._trusted_fortify_capacity(
                fortify_capacity, tainted
            )
            length_value = self._product_value(list(lengths))
            capacity_value = (
                self._eval_int(active_capacity)
                if active_capacity is not None
                else None
            )
            if (
                length_value is not None
                and capacity_value is not None
                and length_value > capacity_value
            ):
                # The fortified callee fails before touching the source.
                continue
            synthetic = Call(
                order=call.order,
                ea=effect.sink_ea,
                name=effect.sink,
                args=(),
                text=call.text,
                origin=call.name,
                block_id=call.block_id,
                guards=call.guards,
            )
            bounded_findings = self._check_source_bounds(
                function, synthetic, source, list(lengths), buffers
            )
            for finding in bounded_findings:
                findings.append(
                    replace(
                        finding,
                        function_ea=effect.function_ea,
                        function_name=effect.function_name,
                        summary=f"{finding.summary} via {call.name}",
                        evidence=f"{finding.evidence}; wrapper={call.name}",
                    )
                )
            tail_findings = (
                []
                if bounded_findings
                else self._check_uninitialized_source_tail(
                    function, synthetic, source, list(lengths), buffers
                )
            )
            for finding in tail_findings:
                findings.append(
                    replace(
                        finding,
                        function_ea=effect.function_ea,
                        function_name=effect.function_name,
                        summary=f"{finding.summary} via {call.name}",
                        evidence=f"{finding.evidence}; wrapper={call.name}",
                    )
                )
            if not bounded_findings and not tail_findings:
                structured = self._check_structured_summary_copy(
                    function, call, synthetic, source, list(lengths)
                )
                if structured is not None:
                    findings.append(
                        replace(
                            structured,
                            function_ea=effect.function_ea,
                            function_name=effect.function_name,
                            evidence=f"{structured.evidence}; wrapper={call.name}",
                        )
                    )
        return findings

    def _check_iovec_reads(
        self,
        function: FunctionIR,
        call: Call,
        buffers: dict[str, BufferInfo],
    ) -> list[Finding]:
        """Check descriptor and payload ranges consumed by writev-family APIs."""

        name = normalize_symbol(call.name)
        consumers: list[
            tuple[str, Expr, Expr, IovecReadEffect | None]
        ] = []
        specification = IOVEC_READ_SPECS.get(name)
        if specification is not None:
            vector_index, count_index = specification
            vectors = self._arg(call, vector_index)
            count = self._arg(call, count_index)
            if vectors is not None and count is not None:
                consumers.append((name, vectors, count, None))
        elif (summary := self._summary_for_call(call)) is not None:
            for effect in summary.iovec_reads:
                vectors = effect.vectors.resolve(call.args)
                count = effect.count.resolve(call.args)
                if vectors is not None and count is not None:
                    consumers.append((effect.sink, vectors, count, effect))

        findings: list[Finding] = []
        for sink, vectors, count, effect in consumers:
            count_value = self._eval_int(count)
            if count_value is not None and (
                count_value <= 0 or count_value > _IOV_MAX
            ):
                # Linux returns EINVAL before reading an invalid vector array.
                continue
            count_bounds = self._effective_integer_bounds(function, call, count)
            if count_bounds is not None and (
                count_bounds[1] <= 0 or count_bounds[0] > _IOV_MAX
            ):
                continue

            pointer_bits = vectors.unwrapped().bits
            pointer_bytes = (
                pointer_bits // 8
                if pointer_bits in {32, 64}
                else 8
            )
            descriptor_size = pointer_bytes * 2
            descriptor_width = Expr(
                kind="const",
                text=str(descriptor_size),
                value=descriptor_size,
                bits=64,
                signed=False,
            )
            synthetic = Call(
                order=call.order,
                ea=effect.sink_ea if effect is not None else call.ea,
                name=sink,
                args=(),
                text=call.text,
                block_id=call.block_id,
                guards=call.guards,
            )
            descriptor_findings = self._check_source_bounds(
                function,
                synthetic,
                vectors,
                [count, descriptor_width],
                buffers,
            )
            resolved_entries = self._resolved_iovec_entries(
                function,
                call,
                vectors,
                count_value,
                pointer_bytes,
                descriptor_size,
            )

            split_descriptor_recovered = (
                bool(descriptor_findings)
                and count_value is not None
                and len(resolved_entries) == count_value
                and all(
                    base_assignment is not None
                    and length_assignment is not None
                    for base_assignment, length_assignment, _, _ in resolved_entries
                )
                and any(
                    split_base or split_length
                    for _, _, split_base, split_length in resolved_entries
                )
            )
            if not split_descriptor_recovered:
                for finding in descriptor_findings:
                    findings.append(
                        self._annotate_iovec_finding(
                            replace(
                                finding,
                                summary=(
                                    f"{sink} reads past the iovec descriptor array"
                                ),
                                evidence=(
                                    f"{finding.evidence}; "
                                    f"iovec_count={count.text or '?'}; "
                                    f"descriptor_size={descriptor_size}"
                                ),
                            ),
                            call,
                            effect,
                        )
                    )

            if self._iovec_total_exceeds_ssize(
                resolved_entries, pointer_bits
            ):
                # Linux validates the aggregate byte count after importing
                # descriptors but before touching any payload.
                continue
            for index, (
                base_assignment,
                length_assignment,
                _,
                _,
            ) in enumerate(resolved_entries):
                if base_assignment is None or length_assignment is None:
                    continue
                source = base_assignment.value
                length = length_assignment.value
                bounded = self._check_source_bounds(
                    function, synthetic, source, [length], buffers
                )
                for finding in bounded:
                    findings.append(
                        self._annotate_iovec_finding(
                            replace(
                                finding,
                                evidence=f"{finding.evidence}; iovec_index={index}",
                            ),
                            call,
                            effect,
                        )
                    )
                if bounded:
                    continue
                output = Call(
                    order=call.order,
                    ea=synthetic.ea,
                    name="write",
                    args=(),
                    text=call.text,
                    block_id=call.block_id,
                    guards=call.guards,
                )
                for finding in self._check_uninitialized_source_tail(
                    function, output, source, [length], buffers
                ):
                    findings.append(
                        self._annotate_iovec_finding(
                            replace(
                                finding,
                                callee=sink,
                                summary=finding.summary.replace(
                                    "write can", f"{sink} can", 1
                                ),
                                evidence=f"{finding.evidence}; iovec_index={index}",
                            ),
                            call,
                            effect,
                        )
                    )
        return findings

